// Single structured error sink for ATLAS.
// Only stage, request id, error shape and an allowlisted operational message are
// emitted. Free-form messages are dropped by default, so a credential, cookie,
// prompt or record body can never reach the log through an error string.
const MAX_MESSAGE = 180;
const OMITTED = '[omitted]';
// Messages are kept only when they describe a known operational failure with no
// user-provided content. Everything else is replaced by OMITTED.
const SAFE_MESSAGES = [
  /^(?:D1_ERROR|Error)?:?\s*(?:no such (?:table|column|function): [A-Za-z0-9_]+)$/u,
  /^(?:D1_ERROR|Error)?:?\s*(?:UNIQUE|CHECK|FOREIGN KEY|NOT NULL) constraint failed[A-Za-z0-9_.]*$/u,
  /^(?:D1_ERROR|Error)?:?\s*SQLITE_[A-Z_]+$/u,
  /^(?:D1_ERROR|Error)?:?\s*(?:The operation was aborted|This operation was aborted|AbortError|network|fetch failed|ECONNRESET|ENOTFOUND|ETIMEDOUT|timeout)$/u,
  /^(?:D1_ERROR|Error)?:?\s*missing replan state$/u,
  /^(?:D1_ERROR|Error)?:?\s*(?:atomic snapshot unavailable|bounds|invalid stored state|invalid budget store|invalid expense store|state changing)$/u
];
const REDACTIONS = [
  /AIza[0-9A-Za-z_-]{10,}/gu,
  /\bBearer\s+[^\s]+/giu,
  /eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}(?:\.[A-Za-z0-9_-]{8,})?/gu,
  /[A-Za-z0-9_-]{32,}/gu
];
const META_LIMITS = {route:80, table:60, kind:40, action:40, stage:60, provider:40};
function scrub(value, max) {
  if (typeof value !== 'string') return '';
  let text = value;
  for (const pattern of REDACTIONS) text = text.replace(pattern, '[redacted]');
  return text.replace(/[\u0000-\u001f\u007f]+/gu, ' ').trim().slice(0, max);
}
function safeMessage(message) {
  if (typeof message !== 'string' || !message.trim()) return '';
  const trimmed = message.trim().slice(0, MAX_MESSAGE);
  return SAFE_MESSAGES.some(pattern => pattern.test(trimmed)) ? scrub(trimmed, MAX_MESSAGE) : OMITTED;
}
// Request ids are always generated by the worker as UUIDs. Anything else is
// dropped rather than logged, so a caller cannot pass a secret as an id.
function safeRequestId(value) {
  return typeof value === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u.test(value) ? value : '';
}
function details(meta) {
  if (!meta || typeof meta !== 'object' || Array.isArray(meta)) return {};
  const out = {};
  for (const [key, value] of Object.entries(meta)) {
    if (!Object.hasOwn(META_LIMITS, key)) continue;
    if (typeof value === 'string') out[key] = scrub(value, META_LIMITS[key]);
    else if (typeof value === 'boolean' || Number.isSafeInteger(value)) out[key] = value;
  }
  return out;
}
// Exported so tests can assert that secrets are stripped and nothing else is kept.
export function describeError(error) {
  const info = error && typeof error === 'object' ? error : {};
  const status = Number.isInteger(info.status) ? info.status : Number.isInteger(info.http) ? info.http : null;
  const code = typeof info.code === 'string' || Number.isSafeInteger(info.code) ? scrub(String(info.code), 40) : '';
  return {
    name: scrub(typeof info.name === 'string' ? info.name : typeof error, 40) || 'Error',
    code,
    ...(status === null ? {} : {status}),
    message: safeMessage(info.message)
  };
}
export function reportError({stage = 'unknown', requestId = '', error, meta} = {}) {
  try {
    console.error(JSON.stringify({
      event: 'atlas_error',
      stage: scrub(stage, META_LIMITS.stage) || 'unknown',
      requestId: safeRequestId(requestId),
      ...describeError(error),
      ...details(meta)
    }));
  } catch {}
}
